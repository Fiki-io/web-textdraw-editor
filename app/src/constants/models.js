/**
 * Returns the primary real image URL for any GTA SA/SA-MP model ID.
 * - Skins (0 - 311): official open.mp transparent PNG
 * - Objects, pickups, food, weapons, items: real 3D render from files.prineside.com
 */
export function getModelImageUrl(modelId) {
  const id = parseInt(modelId, 10)
  if (isNaN(id)) return ''

  // Skins (0 - 311)
  if (id >= 0 && id <= 311) {
    return `https://assets.open.mp/assets/images/skins/${id}.png`
  }

  // All objects, food, drinks, weapons, pickups, interior
  return `https://files.prineside.com/gtasa_samp_model_id/white/${id}_w.jpg`
}

/**
 * Returns alternative candidate fallback URLs if the primary image fails.
 */
export function getModelFallbackUrls(modelId) {
  const id = parseInt(modelId, 10)
  if (isNaN(id)) return []

  const list = []
  if (id >= 0 && id <= 311) {
    list.push(`https://assets.open.mp/assets/images/skins/${id}.png`)
    list.push(`https://files.prineside.com/gtasa_samp_model_id/white/${id}_w.jpg`)
    list.push(`https://files.prineside.com/gtasa_samp_model_id/blue/${id}_b.jpg`)
  } else {
    list.push(`https://files.prineside.com/gtasa_samp_model_id/white/${id}_w.jpg`)
    list.push(`https://files.prineside.com/gtasa_samp_model_id/blue/${id}_b.jpg`)
  }
  return list
}

export function getModelInfo(modelId) {
  const id = parseInt(modelId, 10)
  const found = COMMON_MODELS.find(m => m.id === id)
  if (found) return found
  return {
    id,
    name: `Model ${id}`,
    category: id <= 311 ? 'Skins' : (id >= 400 && id <= 611 ? 'Vehicles' : 'Objects'),
    desc: `SA-MP Model ID ${id}`,
    rotX: 0,
    rotY: 0,
    rotZ: 0,
    zoom: 1.0,
  }
}
